CREATE TABLE ciudadano (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identificacion VARCHAR(10) NOT NULL UNIQUE,
    nombres VARCHAR(100) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    fecha_nacimiento DATE NOT NULL,
    lugar_nacimiento VARCHAR(150) NOT NULL,
    fecha_expedicion DATE NOT NULL,
    lugar_expedicion VARCHAR(150) NOT NULL,
    rh VARCHAR(1) NOT NULL,
    grupo_sanguineo VARCHAR(2) NOT NULL,
    estatura NUMERIC(3, 2) NOT NULL,
    CONSTRAINT ck_ciudadano_rh CHECK (rh IN ('+', '-')),
    CONSTRAINT ck_ciudadano_grupo CHECK (grupo_sanguineo IN ('A', 'B', 'AB', 'O')),
    CONSTRAINT ck_ciudadano_estatura CHECK (estatura BETWEEN 0.50 AND 2.50),
    CONSTRAINT ck_ciudadano_fechas CHECK (fecha_expedicion > fecha_nacimiento)
);

CREATE TABLE antecedente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ciudadano_id BIGINT NOT NULL UNIQUE REFERENCES ciudadano(id),
    estado VARCHAR(20) NOT NULL,
    fuente VARCHAR(50) NOT NULL,
    fecha_actualizacion TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_antecedente_estado CHECK (estado IN ('REQUERIDO', 'NO_REQUERIDO'))
);

CREATE TABLE fuerza_publica (
    codigo VARCHAR(30) PRIMARY KEY,
    nombre VARCHAR(70) NOT NULL
);

CREATE TABLE rango (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fuerza_codigo VARCHAR(30) NOT NULL REFERENCES fuerza_publica(codigo),
    nombre VARCHAR(80) NOT NULL,
    CONSTRAINT uq_rango_fuerza_nombre UNIQUE (fuerza_codigo, nombre)
);

CREATE TABLE perfil (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL UNIQUE,
    nombre VARCHAR(100) NOT NULL
);

CREATE TABLE permiso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(60) NOT NULL UNIQUE,
    nombre VARCHAR(100) NOT NULL
);

CREATE TABLE opcion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(60) NOT NULL UNIQUE,
    nombre VARCHAR(100) NOT NULL,
    ruta VARCHAR(150) NOT NULL
);

CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identificacion VARCHAR(10) NOT NULL UNIQUE,
    nombres VARCHAR(100) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    correo VARCHAR(200) NOT NULL UNIQUE,
    fuerza_codigo VARCHAR(30) REFERENCES fuerza_publica(codigo),
    rango_id BIGINT REFERENCES rango(id),
    id_fuerza VARCHAR(40),
    password_hash VARCHAR(255) NOT NULL,
    activo BOOLEAN NOT NULL,
    fecha_creacion TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE usuario_perfil (
    usuario_id BIGINT NOT NULL REFERENCES usuario(id),
    perfil_id BIGINT NOT NULL REFERENCES perfil(id),
    PRIMARY KEY (usuario_id, perfil_id)
);

CREATE TABLE perfil_permiso (
    perfil_id BIGINT NOT NULL REFERENCES perfil(id),
    permiso_id BIGINT NOT NULL REFERENCES permiso(id),
    PRIMARY KEY (perfil_id, permiso_id)
);

CREATE TABLE opcion_permiso (
    opcion_id BIGINT NOT NULL REFERENCES opcion(id),
    permiso_id BIGINT NOT NULL REFERENCES permiso(id),
    PRIMARY KEY (opcion_id, permiso_id)
);

CREATE TABLE defensa_personal_simulado (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identificacion VARCHAR(10) NOT NULL UNIQUE,
    nombres VARCHAR(100) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    fuerza_codigo VARCHAR(30) NOT NULL REFERENCES fuerza_publica(codigo),
    rango_id BIGINT NOT NULL REFERENCES rango(id),
    id_fuerza VARCHAR(40) NOT NULL,
    activo BOOLEAN NOT NULL
);

CREATE INDEX ix_ciudadano_apellidos ON ciudadano (apellidos, nombres);
CREATE INDEX ix_antecedente_estado ON antecedente (estado);
CREATE INDEX ix_usuario_fuerza ON usuario (fuerza_codigo);
